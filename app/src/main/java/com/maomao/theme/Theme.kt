val LocalThemeMode = staticCompositionLocalOf { 0 } // 0 = system, 1 = light, 2 = dark

@Composable
fun MaoMaoTheme(
    darkTheme: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val view = LocalView.current
    val context = LocalContext.current
    val systemUiController = rememberSystemUiController()

    SideEffect {
        val window = (context as android.app.Activity).window
        WindowCompat.setDecorFitsSystemWindows(window, false)
        
        val statusBarColor = if (darkTheme) colorScheme.background.toArgb() else colorScheme.surfaceContainerLow.toArgb()
        val navBarColor = colorScheme.background.toArgb()
        
        systemUiController.setStatusBarColor(
            color = statusBarColor,
            darkIcons = !darkTheme
        )
        systemUiController.setNavigationBarColor(
            color = navBarColor,
            darkIcons = !darkTheme
        )
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}

